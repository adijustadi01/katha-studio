// Copies the bundled open-licensed fonts into public/fonts and writes fonts.css.
// Indic fonts are registered under "Katha <Script>" families restricted to their
// script's unicode-range so Courier Prime always renders Latin text.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'node_modules/@fontsource');
const out = path.join(root, 'public/fonts');
fs.mkdirSync(out, { recursive: true });

const fonts = [
  { pkg: 'courier-prime', family: 'Courier Prime', subsets: ['latin', 'latin-ext'], styles: ['400-normal', '700-normal', '400-italic', '700-italic'] },
  { pkg: 'noto-sans-tamil', family: 'Katha Tamil', subsets: ['tamil'], styles: ['400-normal', '700-normal'], adjust: '88%' },
  { pkg: 'noto-serif-tamil', family: 'Katha Tamil Serif', subsets: ['tamil'], styles: ['400-normal', '700-normal'], adjust: '88%' },
  { pkg: 'noto-sans-telugu', family: 'Katha Telugu', subsets: ['telugu'], styles: ['400-normal', '700-normal'], adjust: '92%' },
  { pkg: 'noto-serif-telugu', family: 'Katha Telugu Serif', subsets: ['telugu'], styles: ['400-normal', '700-normal'], adjust: '92%' },
  { pkg: 'noto-sans-devanagari', family: 'Katha Devanagari', subsets: ['devanagari'], styles: ['400-normal', '700-normal'], adjust: '92%' },
  { pkg: 'noto-sans-malayalam', family: 'Katha Malayalam', subsets: ['malayalam'], styles: ['400-normal', '700-normal'], adjust: '88%' },
  { pkg: 'noto-sans-kannada', family: 'Katha Kannada', subsets: ['kannada'], styles: ['400-normal', '700-normal'], adjust: '92%' },
];

let css = '/* Generated by scripts/copy-fonts.mjs — fonts are SIL Open Font License 1.1 (see CREDITS.md) */\n';
for (const f of fonts) {
  const cssSrc = fs.readFileSync(path.join(src, f.pkg, '400.css'), 'utf8');
  for (const sub of f.subsets) {
    const block = cssSrc.split('@font-face').find((b) => b.includes(`-${sub}-400-normal.woff2`));
    const range = block?.match(/unicode-range:\s*([^;]+);/)?.[1];
    for (const st of f.styles) {
      const file = `${f.pkg}-${sub}-${st}.woff2`;
      const from = path.join(src, f.pkg, 'files', file);
      if (!fs.existsSync(from)) continue;
      fs.copyFileSync(from, path.join(out, file));
      const [weight, style] = st.split('-');
      css += `@font-face{font-family:'${f.family}';font-style:${style};font-weight:${weight};font-display:block;src:url(./${file}) format('woff2');${range ? `unicode-range:${range};` : ''}${f.adjust ? `size-adjust:${f.adjust};` : ''}}\n`;
    }
  }
  fs.copyFileSync(path.join(src, f.pkg, 'LICENSE'), path.join(out, `LICENSE-${f.pkg}.txt`));
}
fs.writeFileSync(path.join(out, 'fonts.css'), css);
console.log('fonts copied to public/fonts');
