const DICTS: Record<UILang, Record<string, string>> = { en: {}, ta, te };
let current: UILang = 'en';
try {
  const s = localStorage.getItem('katha.uilang') as UILang | null;
  if (s && DICTS[s]) current = s;
} catch {
  /* ignore */
}

export function setUILang(l: UILang) {
  current = l;
  try {
    localStorage.setItem('katha.uilang', l);
  } catch {
    /* ignore */
  }
}
export function uiLang(): UILang {
  return current;
}
export function t(s: string): string {
  return DICTS[current][s] || s;
}
